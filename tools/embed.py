#!/usr/bin/env python3
"""Embed the translator headers into the program.

The first-run module build compiles translated game code against
rec_abi.h, m68k_core.h, rec_gen.h and c31_core.h. Those headers ship
inside the program so the player's machine needs only a C compiler.

Usage: tools/embed.py SRCDIR OUTDIR
Writes OUTDIR/rec_headers.h and OUTDIR/rec_headers.c.
"""
import sys
import os

HEADERS = ["rec_abi.h", "m68k_core.h", "rec_gen.h", "c31_core.h"]


def c_escape(data):
    out = []
    for ch in data:
        o = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif ch == "\n":
            out.append("\\n\"\n\"")
        elif 32 <= o < 127:
            out.append(ch)
        else:
            out.append("\\%03o" % o)
    return "".join(out)


def main():
    srcdir, outdir = sys.argv[1], sys.argv[2]
    os.makedirs(outdir, exist_ok=True)
    blobs = []
    for name in HEADERS:
        with open(os.path.join(srcdir, name), "r", encoding="utf-8") as f:
            blobs.append((name, f.read()))
    with open(os.path.join(outdir, "rec_headers.h"), "w",
              encoding="utf-8") as f:
        f.write("// Generated by tools/embed.py. Do not edit.\n")
        f.write("#pragma once\n")
        f.write("extern int rr_hdr_count;\n")
        f.write("extern const char *rr_hdr_names[];\n")
        f.write("extern const char *rr_hdr_data[];\n")
    with open(os.path.join(outdir, "rec_headers.c"), "w",
              encoding="utf-8") as f:
        f.write("// Generated by tools/embed.py. Do not edit.\n")
        f.write('#include "rec_headers.h"\n')
        f.write("int rr_hdr_count = %d;\n" % len(blobs))
        f.write("const char *rr_hdr_names[] = {\n")
        for name, _ in blobs:
            f.write('    "%s",\n' % name)
        f.write("};\n")
        f.write("const char *rr_hdr_data[] = {\n")
        for _, text in blobs:
            f.write('    "%s",\n' % c_escape(text))
        f.write("};\n")


if __name__ == "__main__":
    main()
