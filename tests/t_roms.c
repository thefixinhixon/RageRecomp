static int check(const char *path, const char *what) {
    rom_file_t by_name = { "t", "test.bin", 0xD465F907u, 4096u };
    rom_file_t by_crc = { "t", "renamed.bin", 0xD465F907u, 4096u };
    rom_file_t absent = { "t", "absent.bin", 0x12345678u, 16u };
    const char *z[1] = { path };
    roms_t *r = roms_open(z, 1);
    uint32_t len = 0, i;
    uint8_t *d;
    int good = 1;
    d = roms_read(r, &by_name, &len);
    T_OK(d && len == 4096u, "%s: read by name", what);
    for (i = 0; d && i < len; i++) good &= d[i] == (uint8_t)(i % 251);
    T_OK(d && good, "%s: data intact", what);
    free(d);
    d = roms_read(r, &by_crc, &len);
    T_OK(d && len == 4096u, "%s: found by CRC under another name", what);
    free(d);
    T_OK(!roms_failed(r), "%s: no problems yet", what);
    d = roms_read(r, &absent, &len);
    T_OK(!d && roms_failed(r), "%s: missing file reported", what);
    roms_close(r);
    return 0;
}

int main(void) {
    static uint8_t data[4096];
    mz_zip_archive zw;
    FILE *f;
    uint32_t i;
    test_init();
    for (i = 0; i < sizeof(data); i++) data[i] = (uint8_t)(i % 251);
    f = fopen("t_roms.7z", "wb");
    fwrite(t7z, 1, sizeof(t7z), f);
    fclose(f);
    check("t_roms.7z", "7z");
    memset(&zw, 0, sizeof(zw));
    T_OK(mz_zip_writer_init_file(&zw, "t_roms.zip", 0) &&
            mz_zip_writer_add_mem(&zw, "a/test.bin", data, sizeof(data), MZ_BEST_COMPRESSION) &&
            mz_zip_writer_finalize_archive(&zw) && mz_zip_writer_end(&zw), "zip written");
    check("t_roms.zip", "zip");
    remove("t_roms.7z");
    remove("t_roms.zip");
    printf("# %d tests, %d failures\n", t_count, t_failures);
    return t_failures != 0;
}
